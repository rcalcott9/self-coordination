"""
Adapter: Stage 1 raw collection CSVs -> the schema T5's analysis/run_stage1.py reads.

Lead-owned. Writes ONLY into analysis_input/ and never touches raw run files or T5's
analysis/ code. The raw CSVs stay the record of what was collected; this is a view.

  python3 to_pipeline.py --set frame
"""
import argparse, csv, glob, json, os, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pc_common as P                                              # noqa: E402

OUT = os.path.join(P.ROOT, "analysis_input")
COLS = ["aid", "perm", "trial", "chosen_item", "chosen_position", "parse_ok", "ok",
        "api_model", "prompt_sha8"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", required=True, choices=["frame", "preflight"])
    args = ap.parse_args()
    src = {"frame": "runs/visual_frame/visual_frame_*.csv",
           "preflight": "runs/liveness_preflight/visual_preflight_*.csv"}[args.set]
    files = sorted(glob.glob(os.path.join(P.ROOT, src)))
    assert files, f"no files matching {src}"

    rows = []
    for f in files:
        rows += list(csv.DictReader(open(f, newline="")))
    print(f"read {len(rows)} rows from {len(files)} file(s)")

    os.makedirs(OUT, exist_ok=True)
    by = collections.defaultdict(list)
    for r in rows:
        by[r["checkpoint_requested"]].append(r)

    panel = {mid: (fam, vin, strat) for fam, mid, vin, strat in P.PANEL}
    models = []
    for mid, rr in sorted(by.items(), key=lambda kv: panel[kv[0]][1]):
        fam, vin, strat = panel[mid]
        dst = os.path.join(OUT, f"{args.set}_{mid}.csv")
        with open(dst, "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=COLS)
            w.writeheader()
            for r in rr:
                ok = r["transport_ok"] == "1"
                # A transport failure never returned a checkpoint, so it carries an empty
                # `api_model` and run_stage1's checkpoint_requested_eq_returned gate counts
                # it as a MISMATCH -- a false FAIL on rows that are already excluded as
                # failed. Transport failures stay in the raw CSVs (the record) and in the
                # ledger; they are not part of the analysis view. Retried trials appear here
                # via their successful row.
                if not ok:
                    continue
                pok = ok and r["parse_ok"] == "1"
                w.writerow(dict(
                    aid=r["array_id"], perm=r["presentation_id"], trial=r["trial"],
                    chosen_item=r["canonical_index"] if pok else "",
                    chosen_position=r["slot_returned"] if pok else "",
                    parse_ok=str(pok), ok=str(ok),
                    api_model=r["checkpoint_returned"], prompt_sha8=r["prompt_hash"]))
        models.append(dict(model_id=mid, family=fam, files=[dst], schema="aid_perm",
                           api_model_contains=mid, vintage_date=vin, stratum=strat))
        print(f"  {mid:28} {len(rr):6d} rows -> {os.path.basename(dst)}")

    # B203's own manifest uses `stimulus_id` and carries no `mechanism` column, which
    # run_stage1 requires. Emit a normalised manifest rather than edit T5's reader or the
    # frozen battery file. family/mechanism come from the collection rows themselves.
    man = os.path.join(OUT, f"manifest_{args.set}.csv")
    seen = {}
    for r in rows:
        seen.setdefault(r["array_id"], (r["family"], r["mechanism"] or r["family"]))
    with open(man, "w", newline="") as fh:
        w = csv.writer(fh); w.writerow(["array_id", "family", "mechanism"])
        for a, (fam, mech) in sorted(seen.items()):
            w.writerow([a, fam, mech])
    print(f"  manifest: {len(seen)} arrays -> {os.path.basename(man)}")

    sources = {
        "_note": (f"Stage 1 {args.set} collection, generated by runners/to_pipeline.py. "
                  "Adapter view of the raw CSVs in runs/; the raw files remain the record. "
                  "Vintage is measured in years since 2025-01, so every slope reads per year. "
                  "thinking=disabled on every Claude call (D-017); GPT control surface varies "
                  "across the ladder and is carried in `stratum` (Threat 13)."),
        "domain": "visual", "k_options": 4,
        "battery_manifest": man,
        "stimuli_root": os.path.join(P.TREE, "study2_4opt_20260830", "stimuli"),
        "expect_prompt_sha8": "d40ea45d", "models": models}
    sp = os.path.join(OUT, f"sources_{args.set}.json")
    json.dump(sources, open(sp, "w"), indent=1)
    print(f"-> {sp}  ({len(models)} models)")


if __name__ == "__main__":
    main()
