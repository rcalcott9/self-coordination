"""GREEN core (Study 3 proposed core): prompts for 2 actual partners x 2 disclosure states. PREPARATION ONLY.

Restores the archived GREEN-match game (study4_relational_staghunt_20260908/code/pilot_prompts.py) verbatim:
the game block, the action question and the prediction question are imported, not retyped, and every
archived prompt that is reused is asserted against its archived sha8. The only new text is the WITHHELD
partner clause. Information is symmetric in every cell: both players get the same kind of description
(both told the other's identity, or neither told). The archived UNKNOWN cell was asymmetric (focal not told,
partner told) and is not used.

Cells (actual partner x disclosure):
  COPY      x DISCLOSED : archived 'copy'  clause, each model paired with itself
  DIFFERENT x DISCLOSED : archived 'other' clause, Claude paired with GPT
  COPY      x WITHHELD  : new withheld clause, each model paired with itself
  DIFFERENT x WITHHELD  : the SAME withheld prompt, Claude paired with GPT
Under WITHHELD the prompt does not depend on the actual partner, so one withheld pool per model serves
both actual partners; only the pairing differs.
"""
import hashlib, os, sys
ARCH = "/Users/calypsocalcott/Desktop/Coordination/Self_Coordination/study4_relational_staghunt_20260908/code"
sys.path.insert(0, ARCH)
import pilot_prompts as PP                      # archived; not modified

ARCHIVED_SHA8 = {  # from pilot/PROMPT_AUDIT.md and the pilot jsonl prompt_sha8 fields
    ("claude", "copy", "action"): "ef91ca28", ("claude", "copy", "predict"): "e289f820",
    ("claude", "other", "action"): "c54aeae8", ("claude", "other", "predict"): "ed1c57e9",
    ("gpt", "other", "action"): "de185e62"}
# generated by the archived builder but never sent in the pilot (GPT was never focal there)
NEVER_SENT = {("gpt", "copy", "action"): "ce258781", ("gpt", "copy", "predict"): "e92b41b4",
              ("gpt", "other", "predict"): "5835d8fe"}

WITHHELD = ("The other player is an AI model. You are not told which model it is or how it was "
            "produced, and it has been told exactly the same about you.")   # NEW TEXT - needs review


def prompt(model, disclosure, arm):
    """disclosure: copy | other (archived clauses) | withheld (new). arm: action | predict."""
    if disclosure in ("copy", "other"):
        return PP.prompt(model, disclosure, arm)
    head = (f"You are {PP.DISPLAY[model]}. You are playing a one-shot coordination game "
            "with ONE other player.\n\n" + WITHHELD + "\n\n")
    return head + PP.GAME + (PP.ACTION_Q if arm == "action" else PP.PREDICT_Q)


def sha8(s):
    return hashlib.sha256(s.encode()).hexdigest()[:8]


CELLS = [(m, d, a) for m in ("claude", "gpt") for d in ("copy", "other", "withheld") for a in ("action", "predict")]


def check():
    for k, v in {**ARCHIVED_SHA8, **NEVER_SENT}.items():
        assert sha8(prompt(*k)) == v, (k, sha8(prompt(*k)), v)
    for m in ("claude", "gpt"):
        w = prompt(m, "withheld", "action")
        o = "gpt" if m == "claude" else "claude"
        assert PP.DISPLAY[o] not in w and "instance" not in w, m          # nothing leaks the partner
        assert prompt(m, "withheld", "action").split("\n\n", 2)[2] == prompt(m, "copy", "action").split("\n\n", 2)[2]
    return {f"{m}|{d}|{a}": sha8(prompt(m, d, a)) for m, d, a in CELLS}


if __name__ == "__main__":
    shas = check()
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = ["# GREEN core - rendered prompts (PREPARATION ONLY; not sent)", "",
           "Archived prompts reused verbatim (sha8 asserted). `withheld` is the only new text.", ""]
    for (m, d, a) in CELLS:
        k = (m, d, a)
        tag = ("archived, sent in pilot" if k in ARCHIVED_SHA8 else
               "archived builder, never sent" if k in NEVER_SENT else "NEW")
        out += [f"## `{m}` / `{d}` / `{a}` - sha8 `{shas[f'{m}|{d}|{a}']}` ({tag})", "", "```", prompt(m, d, a), "```", ""]
    open(os.path.join(here, "prompts", "PROMPTS_RENDERED.md"), "w").write("\n".join(out))
    for k, v in shas.items():
        print(f"{k:26s} {v}")
