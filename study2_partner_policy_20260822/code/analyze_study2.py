def resolve_data(d):
    """Find the runner's output. Refuses to guess between unmerged part files.

    study2_betting.py is resumable: every invocation writes its own
    study2C_<ts>.csv part file, and when more than one part contributes it writes a
    study2C_MERGED_<ts>.csv. Parts can OVERLAP on cells that one invocation left
    partially complete, so blindly concatenating or picking the newest part would
    silently double-count or under-count trials. A MERGED file therefore always
    wins; a single bare part is fine; several bare parts with no MERGED is an error
    the analysis will not paper over.
    """
    merged = [x for x in glob.glob(os.path.join(d, "study2C_MERGED_*.csv"))
              if "_DRY" not in x]
    if merged:
        return max(merged, key=os.path.getmtime)
    parts = [x for x in glob.glob(os.path.join(d, "study2C_*.csv"))
             if "_DRY" not in x and "_MERGED_" not in x]
    if len(parts) == 1:
        return parts[0]
    if len(parts) > 1:
        sys.exit(f"{len(parts)} unmerged part files in {d} and no study2C_MERGED_*.csv:\n  "
                 + "\n  ".join(sorted(os.path.basename(x) for x in parts))
                 + "\nRe-run study2_betting.py so it writes the merge, or pass --data "
                   "explicitly. Concatenating parts here would double-count the cells "
                   "an interrupted run left partially complete.")
    # simulated / hand-named files
    other = [x for x in glob.glob(os.path.join(d, "*.csv")) if "_DRY" not in x]
    return max(other, key=os.path.getmtime) if other else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=None,
                    help="runner CSV; default resolves ../data via resolve_data() "
                         "(newest study2C_MERGED_*, else the single study2C_* part)")
    ap.add_argument("--pairs", default=None,
                    help="pairs table for the pair_id/stimulus_level FALLBACK only; "
                         "default = first of pairs/study2_candidate_pairs.csv, "
                         "pairs/matched_pairs.csv that exists")
    ap.add_argument("--out-dir", default=os.path.join(EXP, "analysis"))
    ap.add_argument("--sample", default="holdout",
                    choices=["holdout", "select", "full"],
                    help="PRIMARY reported sample (pre-registered: holdout)")
    ap.add_argument("--no-bayes", action="store_true")
    ap.add_argument("--perm", type=int, default=PERM)
    ap.add_argument("--boot", type=int, default=BOOT)
    ap.add_argument("--tag", default="")
    args = ap.parse_args()

    pairs_paths = ([args.pairs] if args.pairs else
                   [os.path.join(EXP, "pairs", c) for c in
                    ("study2_candidate_pairs.csv", "matched_pairs.csv")])
    os.makedirs(args.out_dir, exist_ok=True)
    LOG = []

    def log(*a):
        s = " ".join(str(x) for x in a)
        print(s, flush=True)
        LOG.append(s)

    path = args.data or resolve_data(os.path.join(EXP, "data"))
    if not path:
        sys.exit("no Study 2 CSV found (pass --data)")

    log("=" * 79)
    log("STUDY 2 - PARTNER x STIMULUS INTERACTION   (frozen primary analysis)")
    log("=" * 79)
    log(f"  data   : {path}")
    log(f"  schema : {S.assert_matches_psc_common()}")

    rows = load(path, pairs_paths, log)
    actors = sorted(set(r["actor"] for r in rows))
    halves = Counter(r["_half"] for r in rows)
    log(f"  actors : {', '.join(S.DISPLAY.get(a, a) for a in actors)}")
    log(f"  pairs  : " + ", ".join(f"{a}={len(set(r['pair'] for r in rows if r['actor']==a))}"
                                   for a in actors))
    log(f"  split  : select {halves['select']}, holdout {halves['holdout']} trials "
        f"(Study 1 assign_halves; run_id order within cell x variant)")
    log(f"  PRIMARY reported sample: {args.sample.upper()}  "
        f"(pre-registered; select and full printed alongside)")

    cell_out, contrast_out = [], []
    samples = ["holdout", "select", "full"]

    for samp in samples:
        sub = rows if samp == "full" else [r for r in rows if r["_half"] == samp]
        if not sub:
            continue
        cnt = counts_of(sub)
        primary = samp == args.sample
        log("\n" + "=" * 79)
        log(f"SAMPLE = {samp.upper()}   ({len(sub)} trials)"
            + ("   <-- PRIMARY" if primary else "   [secondary, printed for comparison]"))
        log("=" * 79)
        balance_report(cnt, log)

        for a in actors:
            nm = S.DISPLAY.get(a, a)
            pairs_a = sorted(set(k[1] for k in cnt if k[0] == a))
            log(f"\n--- {nm}  ({len(pairs_a)} matched pairs) " + "-" * (40 - len(nm)))

            # ---------------- four cell rates, pooled and by pair -------------
            for scope, pid in [("pooled", None)] + [("pair", p) for p in pairs_a]:
                fc = four_cells(cnt, a, pid)
                ci = bootstrap({k: v for k, v in cnt.items()
                                if pid is None or k[1] == pid}, a, b=args.boot)
                tag = "POOLED over pairs" if pid is None else f"pair {pid}"
                log(f"\n    [{tag}]  P(ATTEMPT), 95% trial bootstrap CI")
                log(f"      {'':10}{'SAME partner':>29}{'DIFFERENT partner':>29}")
                for lvl in ("high", "low"):
                    cells = []
                    for w in S.PARTNERS:
                        k, n = fc[(lvl, w)]
                        lo, hi = prop_ci(k, n, seed=(SEED, a, pid, lvl, w), b=args.boot)
                        cells.append(f"{_rate(k,n):.3f} [{lo:.3f},{hi:.3f}] n={n}")
                    log(f"      {lvl.upper():10}{cells[0]:>29}{cells[1]:>29}")
                    for w in S.PARTNERS:
                        k, n = fc[(lvl, w)]
                        lo, hi = prop_ci(k, n, seed=(SEED, a, pid, lvl, w), b=args.boot)
                        cell_out.append(dict(sample=samp, primary_sample=primary,
                                             actor=a, actor_name=nm,
                                             scope=("pooled" if pid is None else pid),
                                             stimulus_level=lvl, partner=w,
                                             n_attempt=k, n=n,
                                             attempt_rate=(round(k / n, 6) if n else ""),
                                             ci_lo=round(lo, 6), ci_hi=round(hi, 6)))

                c = contrasts_from_cells(fc)
                gs = perm_simple_gap(cnt, a, "same", pid, args.perm)
                gd = perm_simple_gap(cnt, a, "different", pid, args.perm)
                log(f"      gap HIGH-LOW | SAME       {c['gap_same']:+.4f}  "
                    f"95% CI [{ci['gap_same'][0]:+.4f}, {ci['gap_same'][1]:+.4f}]"
                    + (f"   perm p(1-sided)={gs['p_one']:.4f}" if gs else ""))
                log(f"      gap HIGH-LOW | DIFFERENT  {c['gap_diff']:+.4f}  "
                    f"95% CI [{ci['gap_diff'][0]:+.4f}, {ci['gap_diff'][1]:+.4f}]"
                    + (f"   perm p(1-sided)={gd['p_one']:.4f}" if gd else ""))

                # ---------------- the primary test ---------------------------
                pp = perm_partner(cnt, a, pid, args.perm)
                ps = perm_stimulus(cnt, a, pid, args.perm)
                sm = stratum_mean_interaction(cnt, a, pid)
                star = "*" if pp and pp["inter_p_one"] < 0.05 else " "
                log(f"    {star} INTERACTION (gap_SAME - gap_DIFF)  {c['interaction']:+.4f}"
                    f"  95% CI [{ci['interaction'][0]:+.4f}, {ci['interaction'][1]:+.4f}]")
                if pp:
                    log(f"        permute PARTNER within (pair x level x payoff), "
                        f"{pp['n_strata']} strata, {pp['n_perm']} draws")
                    log(f"        p one-sided (PRIMARY) = {pp['inter_p_one']:.4f}   "
                        f"p two-sided = {pp['inter_p_two']:.4f}   "
                        f"null SD = {pp['null_sd_inter']:.4f}")
                if ps:
                    log(f"        sensitivity, permute STIMULUS label: "
                        f"p one-sided = {ps['p_one']:.4f}  p two-sided = {ps['p_two']:.4f}")
                log(f"        stratum-mean version {sm:+.4f}  "
                    f"(identical to the pooled value under balance; any gap is "
                    f"imbalance, not signal)")

                starm = "*" if pp and pp["main_p_two"] < 0.05 else " "
                log(f"    {starm} PARTNER MAIN EFFECT (SAME - DIFFERENT)  "
                    f"{c['partner_main']:+.4f}  95% CI "
                    f"[{ci['partner_main'][0]:+.4f}, {ci['partner_main'][1]:+.4f}]")
                if pp:
                    log(f"        p two-sided (PRIMARY) = {pp['main_p_two']:.4f}   "
                        f"p one-sided = {pp['main_p_one']:.4f}")
                log("        A partner main effect is NOT evidence for the primary "
                    "hypothesis; it is the alternative the primary must beat.")

                contrast_out.append(dict(
                    sample=samp, primary_sample=primary, actor=a, actor_name=nm,
                    scope=("pooled" if pid is None else pid),
                    p_high_same=round(c["p"][("high", "same")], 6),
                    p_low_same=round(c["p"][("low", "same")], 6),
                    p_high_diff=round(c["p"][("high", "different")], 6),
                    p_low_diff=round(c["p"][("low", "different")], 6),
                    gap_same=round(c["gap_same"], 6),
                    gap_same_ci_lo=round(ci["gap_same"][0], 6),
                    gap_same_ci_hi=round(ci["gap_same"][1], 6),
                    gap_same_perm_p_one=(round(gs["p_one"], 6) if gs else ""),
                    gap_diff=round(c["gap_diff"], 6),
                    gap_diff_ci_lo=round(ci["gap_diff"][0], 6),
                    gap_diff_ci_hi=round(ci["gap_diff"][1], 6),
                    gap_diff_perm_p_one=(round(gd["p_one"], 6) if gd else ""),
                    interaction=round(c["interaction"], 6),
                    interaction_ci_lo=round(ci["interaction"][0], 6),
                    interaction_ci_hi=round(ci["interaction"][1], 6),
                    interaction_perm_p_one=(round(pp["inter_p_one"], 6) if pp else ""),
                    interaction_perm_p_two=(round(pp["inter_p_two"], 6) if pp else ""),
                    interaction_sens_stimperm_p_one=(round(ps["p_one"], 6) if ps else ""),
                    interaction_stratum_mean=round(sm, 6) if sm == sm else "",
                    partner_main=round(c["partner_main"], 6),
                    partner_main_ci_lo=round(ci["partner_main"][0], 6),
                    partner_main_ci_hi=round(ci["partner_main"][1], 6),
                    partner_main_perm_p_two=(round(pp["main_p_two"], 6) if pp else ""),
                    partner_main_perm_p_one=(round(pp["main_p_one"], 6) if pp else ""),
                    n_perm=args.perm, n_boot=args.boot))

            # ------------- pair-cluster CI on the primary contrast ------------
            cl = bootstrap(cnt, a, b=min(args.boot, 2000), cluster_pairs=True)
            if cl:
                log(f"\n    pair-clustered 95% CI on the interaction "
                    f"[{cl['interaction'][0]:+.4f}, {cl['interaction'][1]:+.4f}]  "
                    f"({len(pairs_a)} pairs)")
                log("      Generalisation interval: resamples whole matched pairs. With "
                    f"{len(pairs_a)} pairs it is EXTREMELY coarse and is reported as a "
                    "caution, not as the headline CI.")

    # ------------------------------------------------------- Bayesian --------
    bay = None
    if not args.no_bayes:
        log("\n" + "=" * 79)
        log("CONVERGENT BAYESIAN MODEL   (secondary)")
        log("=" * 79)
        bsub = rows if args.sample == "full" else [r for r in rows if r["_half"] == args.sample]
        cnt_b = counts_of(bsub)
        ok, per_actor, info = identifiability_gate(cnt_b, actors, log)
        if ok:
            bay = bayes_fit(bsub, actors, log)
        else:
            bay = dict(reported=False, reason="identifiability gate failed", **info)

    # ------------------------------------------------------------ write ------
    tag = f"_{args.tag}" if args.tag else ""
    def dump(name, rowsx):
        if not rowsx:
            return
        p = os.path.join(args.out_dir, name)
        with open(p, "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rowsx[0]))
            w.writeheader(); w.writerows(rowsx)
        log(f"  -> {p}")

    log("\n" + "=" * 79)
    dump(f"study2_cell_rates{tag}.csv", cell_out)
    dump(f"study2_contrasts{tag}.csv", contrast_out)
    if bay and bay.get("rows"):
        dump(f"study2_bayes{tag}.csv", bay["rows"])
    if bay is not None:
        with open(os.path.join(args.out_dir, f"study2_bayes_status{tag}.json"), "w") as fh:
            json.dump({k: v for k, v in bay.items() if k != "rows"}, fh, indent=2)
    with open(os.path.join(args.out_dir, f"study2_analysis_log{tag}.txt"), "w") as fh:
        fh.write("\n".join(LOG) + "\n")
    print(f"  -> {os.path.join(args.out_dir, f'study2_analysis_log{tag}.txt')}")


if __name__ == "__main__":
    main()
