def _seed(*parts):
    """Deterministic 63-bit seed from any parts.

    NOT Python's built-in hash(): str.__hash__ is salted per process
    (PYTHONHASHSEED), so seeding an RNG from it would give a DIFFERENT reference
    distribution on every run and the frozen analysis would not be reproducible.
    """
    h = hashlib.sha256("|".join(repr(x) for x in parts).encode()).hexdigest()
    return int(h[:16], 16) % (2 ** 63)


# =============================================================== loading ======
def _truthy(v):
    return str(v).strip().lower() in ("true", "1", "yes", "t")


def _resolve_aliases(fieldnames):
    """Map canonical column -> the name actually present, using schema aliases."""
    present = set(fieldnames)
    resolved = {}
    for canon in set(S.COLS) | set(S.ALIASES):
        if canon in present:
            resolved[canon] = canon
            continue
        for alt in S.ALIASES.get(canon, []):
            if alt in present:
                resolved[canon] = alt
                break
    return resolved


def _norm_level(v):
    """Accept {'high','low'} or a 0/1 is_high flag."""
    s = str(v).strip().lower()
    if s in ("high", "hi", "h"):
        return "high"
    if s in ("low", "lo", "l"):
        return "low"
    if s in ("1", "true", "t", "yes"):
        return "high"
    if s in ("0", "false", "f", "no"):
        return "low"
    return ""


def load_pairs(paths, log=None):
    """Pairs-table FALLBACK for pair_id/stimulus_level, tried in order.

    Only used when the runner did not emit the two columns itself. Each candidate is
    tried in turn and the first one that yields at least one APPROVED pair wins. A
    file that exists but is entirely unapproved is reported explicitly rather than
    treated as absent - Study 1's convention is that `approved` is a human decision,
    and at the time of writing all 210 rows of study2_candidate_pairs.csv are
    approved=False, which is a state the analysis should name, not shrug at.
    """
    if isinstance(paths, str):
        paths = [paths]
    for path in paths:
        if not path or not os.path.exists(path):
            continue
        rows = list(csv.DictReader(open(path)))
        approved = [r for r in rows
                    if "approved" not in r or _truthy(r.get("approved", "true"))]
        if not approved:
            if log:
                log(f"  pairs fallback: {path} has {len(rows)} rows but 0 approved "
                    "(approved is a human decision, as in Study 1) - trying the next")
            continue
        out = {}
        for r in approved:
            m = r.get("focal_model") or r.get("actor_model")
            pid = r.get("pair_id") or f"{m}__{r['stimulus_high']}__vs__{r['stimulus_low']}"
            out[(m, r["stimulus_high"])] = (pid, "high")
            out[(m, r["stimulus_low"])] = (pid, "low")
        if log:
            log(f"  pairs fallback: {path} -> {len(approved)} approved pairs")
        return out
    return {}


def assign_halves(rows, cellkey):
    """Study 1's split, verbatim in logic (analyze_stage_ab.assign_halves).

    Within (cell, variant) rows are ordered by run_id and cut in half, so each half
    is exactly AB/BA balanced and the split is reproducible from the data alone with
    no extra seed.
    """
    groups = defaultdict(list)
    for r in rows:
        groups[(cellkey(r), r.get("variant", ""))].append(r)
    for g in groups.values():
        g.sort(key=lambda r: r.get("run_id", ""))
        half = len(g) // 2
        for i, r in enumerate(g):
            r["_half"] = "select" if i < half else "holdout"
    return rows


def check_partner_naming(names, self_names, log):
    """Confirm partner_condition and partner_model_named agree.

    A crossed condition label is the single most damaging possible runner bug for
    this design: it would silently invert the primary contrast. So it is checked
    rather than trusted, and the check is ANCHORED, not merely internally consistent.

    WHY AN ANCHOR IS REQUIRED. A first version of this check tested only structural
    consistency - that each arm names one model, that the two arms differ, and that
    an actor's SAME partner is the other actor's DIFFERENT partner. A simulated
    dataset with the partner_condition column swapped on EVERY row passed all three,
    because a global relabelling is internally consistent by construction. Structural
    consistency cannot detect it; only something tied to the actor's own identity can.

    THE ANCHOR IS IN THE DATA, NOT HARD-CODED. `actor_model_name` is the actor's own
    display string on the same row, so under partner_condition="same" the partner
    named must be exactly that string. This is env-independent: psc_common takes the
    display names from PSC_GPT_NAME / PSC_CLAUDE_NAME, so a hard-coded "GPT-5.5"
    would fire on a correct run that merely renamed the models, while the row's own
    actor_model_name renames with it. S.DISPLAY is used only if the column is absent.
    """
    if not names:
        return
    actors = sorted(set(a for a, _ in names))
    for a in actors:
        for w in S.PARTNERS:
            v = names.get((a, w), set())
            if len(v) > 1:
                sys.exit(f"REFUSING TO RUN: actor {a}, partner_condition={w} names "
                         f"{len(v)} different partner models {sorted(v)}. "
                         "partner_model_named must be constant within an arm.")
        vs, vd = names.get((a, "same"), set()), names.get((a, "different"), set())
        if vs and vd and vs == vd:
            sys.exit(f"REFUSING TO RUN: actor {a} names the SAME partner model "
                     f"{sorted(vs)} in both conditions. The manipulation did not "
                     "reach the prompt.")
        # THE ANCHOR.
        own = sorted(self_names.get(a, set()))
        anchor = own[0] if len(own) == 1 else S.DISPLAY.get(a)
        src = "actor_model_name" if len(own) == 1 else "study2_schema.DISPLAY"
        if len(own) > 1:
            sys.exit(f"REFUSING TO RUN: actor {a} has {len(own)} distinct "
                     f"actor_model_name values {own}.")
        if anchor and vs and sorted(vs)[0] != anchor:
            sys.exit(
                f"REFUSING TO RUN: actor {a} under partner_condition='same' is told "
                f"its partner is {sorted(vs)[0]!r}, but its own name ({src}) is "
                f"{anchor!r}.\n"
                "  The condition labels are crossed, or the prompt named the wrong "
                "model. Either inverts the primary contrast and invalidates the whole "
                "design.")
        if anchor and vd and sorted(vd)[0] == anchor:
            sys.exit(
                f"REFUSING TO RUN: actor {a} under partner_condition='different' is "
                f"told its partner is {sorted(vd)[0]!r}, which is its own name.")
    if len(actors) == 2:
        a, b = actors
        if (names.get((a, "same")) and names.get((b, "different"))
                and names[(a, "same")] != names[(b, "different")]):
            sys.exit(f"REFUSING TO RUN: {a}'s SAME partner {sorted(names[(a,'same')])} "
                     f"!= {b}'s DIFFERENT partner {sorted(names[(b,'different')])}.")
    log("  partner naming: anchored on actor_model_name and consistent - " + "; ".join(
        f"{a}/{w}->{sorted(names[(a, w)])[0]}" for a in actors for w in S.PARTNERS
        if names.get((a, w))))


def load(path, pairs_path, log):
    raw = list(csv.DictReader(open(path)))
    if not raw:
        sys.exit(f"{path}: no rows")
    col = _resolve_aliases(raw[0].keys())

    missing = [c for c in S.REQUIRED if c not in col]
    if missing:
        sys.exit(f"{path}: missing required column(s) {missing}\n"
                 f"  present: {sorted(raw[0].keys())}\n"
                 f"  see study2_schema.py for the frozen schema and accepted aliases")

    pairs_tbl = load_pairs(pairs_path, log)
    have_pair_cols = "pair_id" in col and "stimulus_level" in col
    if not have_pair_cols and not pairs_tbl:
        sys.exit("the data has no pair_id + stimulus_level columns, and no candidate "
                 "pairs table yielded an approved pair:\n  "
                 + "\n  ".join(str(x) for x in pairs_path)
                 + "\n  The analysis will not guess which stimulus of a pair is the "
                   "HIGH one.")
    log("  pair/level source: " + ("runner columns" if have_pair_cols
                                   else "pairs-table fallback"))

    # --- validity filter, re-derived, not trusted -----------------------------
    disagree = 0
    kept = []
    for r in raw:
        derived = (not _truthy(r[col["superseded_by_retry"]])) and _truthy(r[col["valid_response"]])
        if derived != _truthy(r[col["included_in_analysis"]]):
            disagree += 1
        if not derived:
            continue
        kept.append(r)
    if disagree:
        sys.exit(f"REFUSING TO RUN: {disagree} rows where included_in_analysis != "
                 "(not superseded_by_retry) and valid_response.\n"
                 "  The retry policy or the runner's filter column is broken; fix the "
                 "runner, do not analyse this file.")
    log(f"  {len(raw)} raw rows -> {len(kept)} valid, non-superseded trials "
        f"(included_in_analysis re-derived and confirmed)")

    # --- build the analysis rows ---------------------------------------------
    out, bad_partner, bad_level = [], 0, 0
    names = defaultdict(set)
    self_names = defaultdict(set)
    for r in kept:
        actor = r[col["actor_model"]]
        sid = r[col["stimulus"]]
        w = str(r[col["partner_condition"]]).strip().lower()
        if w not in S.PARTNERS:
            bad_partner += 1
            continue
        if have_pair_cols:
            pid = r[col["pair_id"]]
            lvl = _norm_level(r[col["stimulus_level"]])
        else:
            pid, lvl = pairs_tbl.get((actor, sid), ("", ""))
        if lvl not in S.LEVELS or not pid:
            bad_level += 1
            continue
        if "partner_model_named" in col:
            names[(actor, w)].add(str(r[col["partner_model_named"]]).strip())
            if "actor_model_name" in col:
                self_names[actor].add(str(r[col["actor_model_name"]]).strip())
        dec = str(r[col["participation_decision"]]).strip().upper()
        out.append(dict(
            actor=actor, stimulus=sid, pair=pid, level=lvl, partner=w,
            safe=int(float(r[col["safe_payoff"]])),
            y=1 if dec == "ATTEMPT" else 0,
            run_id=r.get(col.get("run_id", "run_id"), ""),
            variant=r.get(col.get("variant", "variant"), ""),
        ))
    if bad_partner:
        log(f"  !! {bad_partner} rows dropped: partner_condition not in {S.PARTNERS}")
    if bad_level:
        log(f"  !! {bad_level} rows dropped: no pair/stimulus_level resolvable")
    check_partner_naming(names, self_names, log)
    if not out:
        sys.exit("no analysable trials after filtering")

    assign_halves(out, lambda r: (r["actor"], r["stimulus"], r["partner"], r["safe"]))
    return out


