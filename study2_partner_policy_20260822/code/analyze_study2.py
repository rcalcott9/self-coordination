def counts_of(rows):
    """(actor, pair, level, partner, safe) -> [k, n], from raw integers only."""
    c = defaultdict(lambda: [0, 0])
    for r in rows:
        key = (r["actor"], r["pair"], r["level"], r["partner"], r["safe"])
        c[key][0] += r["y"]
        c[key][1] += 1
    return {k: tuple(v) for k, v in sorted(c.items())}


def balance_report(cnt, log):
    """Report the cell-size structure and say what it does to the pooled estimand.

    Under a fully balanced design, pooled-count contrasts equal unweighted stratum
    means, which is the whole justification for pooling counts across pairs and
    payoffs - so it is checked, not assumed.

    TWO DIFFERENT KINDS OF IMBALANCE, which must not be confused:

    DESIGNED. The runner accepts a per-payoff allocation from design/*.json (e.g.
    10/10/40/40 across S = 3/5/7/9, concentrating trials where the payoff grid is
    informative). Then n is constant within a payoff level but differs between them.
    This is intentional and harmless to VALIDITY - the permutation test strata by
    payoff and stays exact under any allocation - but it does change the pooled
    ESTIMAND from an equal-weight average over payoffs to an n-weighted one. The
    pooled-count value stays primary, because it is the statistic the permutation
    test is built on and the efficient one; the unweighted stratum mean is printed
    beside every contrast so the difference is visible.

    RAGGED. n varies WITHIN a payoff level, i.e. some cells lost trials to failed
    retries or the select/holdout cut landed unevenly. Small and unavoidable; large
    and it means the runner did not finish, which is worth knowing before reading
    any effect.
    """
    ns = sorted(set(n for _, n in cnt.values()))
    by_safe = defaultdict(set)
    for (a, p, l, w, s), (k, n) in cnt.items():
        by_safe[s].add(n)
    if len(ns) == 1:
        log(f"  design balance: every cell has n={ns[0]}  -> pooled-count contrasts "
            "equal the unweighted stratum means exactly")
        return True
    designed = all(len(v) == 1 for v in by_safe.values())
    alloc = ", ".join(f"S{s}: n={sorted(v)[0] if len(v)==1 else str(min(v))+'-'+str(max(v))}"
                      for s, v in sorted(by_safe.items()))
    if designed:
        log(f"  design balance: NON-UNIFORM BY DESIGN ({alloc}). n is constant within "
            "each payoff level, so this is the runner's allocation, not dropout. The "
            "permutation test is unaffected (it strata by payoff); the pooled estimand "
            "is n-weighted across payoffs and the unweighted stratum mean is printed "
            "beside every contrast.")
    else:
        log(f"  design RAGGED: cell n varies WITHIN payoff levels ({alloc}). Not an "
            "allocation - either trials lost to failed retries, the select/holdout cut "
            "landing unevenly on an odd cell count (expected, and small), or a run that "
            "did not finish (not small, and worth checking before reading any effect). "
            "Pooled-count and stratum-mean contrasts will differ; BOTH are reported and "
            "any gap between them is imbalance, not signal.")
    return False


# ============================================== contrasts from raw counts =====
def _rate(k, n):
    return (k / n) if n else float("nan")


def four_cells(cnt, actor, pair=None):
    """Pooled integer counts for the four (level x partner) cells."""
    out = {}
    for lvl in S.LEVELS:
        for w in S.PARTNERS:
            k = n = 0
            for (a, p, l, ww, _s), (kk, nn) in cnt.items():
                if a == actor and l == lvl and ww == w and (pair is None or p == pair):
                    k += kk
                    n += nn
            out[(lvl, w)] = (k, n)
    return out


def contrasts_from_cells(fc):
    """gap_same, gap_diff, interaction, partner main effect - all from counts."""
    p = {kk: _rate(*v) for kk, v in fc.items()}
    gap_same = p[("high", "same")] - p[("low", "same")]
    gap_diff = p[("high", "different")] - p[("low", "different")]
    kS = fc[("high", "same")][0] + fc[("low", "same")][0]
    nS = fc[("high", "same")][1] + fc[("low", "same")][1]
    kD = fc[("high", "different")][0] + fc[("low", "different")][0]
    nD = fc[("high", "different")][1] + fc[("low", "different")][1]
    return dict(p=p, gap_same=gap_same, gap_diff=gap_diff,
                interaction=gap_same - gap_diff,
                partner_main=_rate(kS, nS) - _rate(kD, nD))


def stratum_mean_interaction(cnt, actor, pair=None):
    """Unweighted mean over (pair x safe) strata of the within-stratum DoD.

    Identical to the pooled-count version under balance; printed as the imbalance
    check, never as a second bite at the primary.
    """
    strata = defaultdict(dict)
    for (a, p, l, w, s), (k, n) in cnt.items():
        if a != actor or (pair is not None and p != pair):
            continue
        strata[(p, s)][(l, w)] = (k, n)
    vals = []
    for cells in strata.values():
        if len(cells) < 4:
            continue
        r = {kk: _rate(*v) for kk, v in cells.items()}
        vals.append((r[("high", "same")] - r[("low", "same")])
                    - (r[("high", "different")] - r[("low", "different")]))
    return float(np.mean(vals)) if vals else float("nan")


# ================================================== permutation machinery =====
def _perm_strata_partner(cnt, actor, pair=None):
    """One stratum per (pair x level x safe): the finest cell the 2x2 crosses over."""
    st = defaultdict(dict)
    for (a, p, l, w, s), (k, n) in cnt.items():
        if a != actor or (pair is not None and p != pair):
            continue
        st[(p, l, s)][w] = (k, n)
    rec = []
    for (p, l, s), d in sorted(st.items()):
        if "same" not in d or "different" not in d:
            continue
        kS, nS = d["same"]
        kD, nD = d["different"]
        if nS == 0 or nD == 0:
            continue
        rec.append((l, kS, nS, kD, nD))
    return rec


def _perm_strata_stimulus(cnt, actor, pair=None):
    """Sensitivity: one stratum per (pair x partner x safe); permute the LEVEL label."""
    st = defaultdict(dict)
    for (a, p, l, w, s), (k, n) in cnt.items():
        if a != actor or (pair is not None and p != pair):
            continue
        st[(p, w, s)][l] = (k, n)
    rec = []
    for (p, w, s), d in sorted(st.items()):
        if "high" not in d or "low" not in d:
            continue
        kH, nH = d["high"]
        kL, nL = d["low"]
        if nH == 0 or nL == 0:
            continue
        rec.append((w, kH, nH, kL, nL))
    return rec


def _hyper(rng, kA, nA, kB, nB, nperm):
    """Exact conditional resampling of the A/B label within each stratum.

    Shuffling a stratum's 0/1 outcomes between the A and B arms and counting the
    successes that land in A is, conditional on the stratum totals, exactly
    Hypergeometric(ngood=k_tot, nbad=n_tot-k_tot, nsample=nA).  Drawing it directly
    is the same reference distribution as an explicit shuffle, computed in integers
    and without a rounding step anywhere.  For a single stratum it is Fisher's exact
    test.
    """
    ktot = kA + kB
    ntot = nA + nB
    kA_star = rng.hypergeometric(ktot, ntot - ktot, nA, size=(nperm, len(nA)))
    return kA_star, ktot - kA_star


def _pvals(obs, draws, tol=TOL):
    """One-sided (upper) and two-sided permutation p, ties INCLUDED, +1 correction."""
    n = len(draws)
    ge = int(np.sum(draws >= obs - tol))
    two = int(np.sum(np.abs(draws) >= abs(obs) - tol))
    return (ge + 1) / (n + 1), (two + 1) / (n + 1)


def perm_partner(cnt, actor, pair=None, nperm=PERM, seed=SEED):
    """Permute PARTNER within (pair x level x safe). Returns interaction + main effect.

    One stream serves both statistics because both are tested against the SAME
    null - "the partner label had no effect" - so they are two functionals of one
    reference distribution, not two separate tests sharing a seed by accident.
    """
    rec = _perm_strata_partner(cnt, actor, pair)
    if not rec:
        return None
    lvl = np.array([r[0] for r in rec])
    kS = np.array([r[1] for r in rec]); nS = np.array([r[2] for r in rec])
    kD = np.array([r[3] for r in rec]); nD = np.array([r[4] for r in rec])
    hi = (lvl == "high").astype(float)
    lo = 1.0 - hi

    def stat(kS_, kD_):
        pHS = (kS_ * hi).sum(-1) / max((nS * hi).sum(), 1)
        pLS = (kS_ * lo).sum(-1) / max((nS * lo).sum(), 1)
        pHD = (kD_ * hi).sum(-1) / max((nD * hi).sum(), 1)
        pLD = (kD_ * lo).sum(-1) / max((nD * lo).sum(), 1)
        return ((pHS - pLS) - (pHD - pLD),
                kS_.sum(-1) / nS.sum() - kD_.sum(-1) / nD.sum())

    obs_i, obs_m = stat(kS.astype(float), kD.astype(float))
    rng = np.random.default_rng(_seed(seed, "partner", actor, pair))
    kS_s, kD_s = _hyper(rng, kS, nS, kD, nD, nperm)
    d_i, d_m = stat(kS_s.astype(float), kD_s.astype(float))
    p1_i, p2_i = _pvals(obs_i, d_i)
    p1_m, p2_m = _pvals(obs_m, d_m)
    return dict(n_strata=len(rec), n_perm=nperm,
                interaction=float(obs_i), inter_p_one=p1_i, inter_p_two=p2_i,
                partner_main=float(obs_m), main_p_one=p1_m, main_p_two=p2_m,
                null_sd_inter=float(np.std(d_i)), null_sd_main=float(np.std(d_m)))


def perm_stimulus(cnt, actor, pair=None, nperm=PERM, seed=SEED):
    """SENSITIVITY: permute the STIMULUS level within (pair x partner x safe).

    Reported, never substituted for the primary. See the module docstring for why
    this is the rejected-as-primary mirror image.
    """
    rec = _perm_strata_stimulus(cnt, actor, pair)
    if not rec:
        return None
    w = np.array([r[0] for r in rec])
    kH = np.array([r[1] for r in rec]); nH = np.array([r[2] for r in rec])
    kL = np.array([r[3] for r in rec]); nL = np.array([r[4] for r in rec])
    sm = (w == "same").astype(float)
    df = 1.0 - sm

    def stat(kH_, kL_):
        pHS = (kH_ * sm).sum(-1) / max((nH * sm).sum(), 1)
        pLS = (kL_ * sm).sum(-1) / max((nL * sm).sum(), 1)
        pHD = (kH_ * df).sum(-1) / max((nH * df).sum(), 1)
        pLD = (kL_ * df).sum(-1) / max((nL * df).sum(), 1)
        return (pHS - pLS) - (pHD - pLD)

    obs = stat(kH.astype(float), kL.astype(float))
    rng = np.random.default_rng(_seed(seed, "stimulus", actor, pair))
    kH_s, kL_s = _hyper(rng, kH, nH, kL, nL, nperm)
    d = stat(kH_s.astype(float), kL_s.astype(float))
    p1, p2 = _pvals(obs, d)
    return dict(interaction=float(obs), p_one=p1, p_two=p2, n_strata=len(rec))


def perm_simple_gap(cnt, actor, partner, pair=None, nperm=PERM, seed=SEED):
    """HIGH-LOW gap within one partner condition; permute LEVEL within (pair x safe).

    This is Study 1's primary test re-run inside each arm of the new factor. It is
    descriptive support for the interaction, not an independent confirmation of it.
    """
    rec = [r for r in _perm_strata_stimulus(cnt, actor, pair) if r[0] == partner]
    if not rec:
        return None
    kH = np.array([r[1] for r in rec]); nH = np.array([r[2] for r in rec])
    kL = np.array([r[3] for r in rec]); nL = np.array([r[4] for r in rec])

    def stat(a, b):
        return a.sum(-1) / nH.sum() - b.sum(-1) / nL.sum()

    obs = stat(kH.astype(float), kL.astype(float))
    rng = np.random.default_rng(_seed(seed, "gap", actor, partner, pair))
    kH_s, kL_s = _hyper(rng, kH, nH, kL, nL, nperm)
    d = stat(kH_s.astype(float), kL_s.astype(float))
    p1, p2 = _pvals(obs, d)
    return dict(gap=float(obs), p_one=p1, p_two=p2)


# =================================================== bootstrap confidence =====
def _boot_cells(cnt, actor):
    keys = [k for k in cnt if k[0] == actor]
    k = np.array([cnt[x][0] for x in keys])
    n = np.array([cnt[x][1] for x in keys])
    return keys, k, n


def _stats_from_draw(keys, kstar, n):
    """Rebuild the four cells and every contrast from one bootstrap replicate."""
    acc = {(l, w): [0.0, 0.0] for l in S.LEVELS for w in S.PARTNERS}
    for i, key in enumerate(keys):
        cell = (key[2], key[3])
        acc[cell][0] += kstar[i]
        acc[cell][1] += n[i]
    p = {c: (v[0] / v[1] if v[1] else float("nan")) for c, v in acc.items()}
    gs = p[("high", "same")] - p[("low", "same")]
    gd = p[("high", "different")] - p[("low", "different")]
    kS = acc[("high", "same")][0] + acc[("low", "same")][0]
    nS = acc[("high", "same")][1] + acc[("low", "same")][1]
    kD = acc[("high", "different")][0] + acc[("low", "different")][0]
    nD = acc[("high", "different")][1] + acc[("low", "different")][1]
    return dict(p_HS=p[("high", "same")], p_LS=p[("low", "same")],
                p_HD=p[("high", "different")], p_LD=p[("low", "different")],
                gap_same=gs, gap_diff=gd, interaction=gs - gd,
                partner_main=(kS / nS if nS else float("nan"))
                             - (kD / nD if nD else float("nan")))


def bootstrap(cnt, actor, b=BOOT, seed=SEED, cluster_pairs=False):
    """Percentile bootstrap CIs.

    TRIAL bootstrap (cluster_pairs=False, PRIMARY for the cell rates): resample
    trials with replacement inside each cell, holding cell n fixed. Resampling n
    Bernoulli draws from a cell with k successes is exactly Binomial(n, k/n), so it
    is drawn directly - again in integers, with no rounded rate anywhere. This CI is
    conditional on THIS stimulus set: it answers "how precise is the estimate for
    these pairs", not "would it hold for other stimuli".

    PAIR-CLUSTER bootstrap (cluster_pairs=True): resample whole matched pairs with
    replacement first, mirroring Study 1's stimulus-clustered bootstrap. This is the
    honest generalisation interval, but with only 2-3 pairs per actor it is EXTREMELY
    coarse - a handful of distinct resamples - and it is labelled as such rather than
    quietly presented as a normal CI.
    """
    keys, k, n = _boot_cells(cnt, actor)
    if not keys:
        return None
    rng = np.random.default_rng(_seed(seed, "boot", actor, cluster_pairs))
    phat = np.where(n > 0, k / np.maximum(n, 1), 0.0)
    draws = defaultdict(list)
    if not cluster_pairs:
        K = rng.binomial(n, phat, size=(b, len(n)))
        for i in range(b):
            for kk, v in _stats_from_draw(keys, K[i], n).items():
                draws[kk].append(v)
    else:
        pairs = sorted(set(x[1] for x in keys))
        by_pair = {p: [i for i, x in enumerate(keys) if x[1] == p] for p in pairs}
        for _ in range(b):
            pick = rng.choice(len(pairs), size=len(pairs), replace=True)
            idx = np.concatenate([by_pair[pairs[j]] for j in pick])
            kk_ = rng.binomial(n[idx], phat[idx])
            for kk, v in _stats_from_draw([keys[i] for i in idx], kk_, n[idx]).items():
                draws[kk].append(v)
    out = {}
    for kk, v in draws.items():
        a = np.asarray(v, dtype=float)
        a = a[np.isfinite(a)]
        out[kk] = (float(np.percentile(a, 2.5)), float(np.percentile(a, 97.5))) \
            if len(a) else (float("nan"), float("nan"))
    return out


def prop_ci(k, n, seed, b=BOOT):
    """Binomial percentile CI for one cell rate, from the raw counts."""
    if not n:
        return float("nan"), float("nan")
    rng = np.random.default_rng(_seed(seed, k, n))
    d = rng.binomial(n, k / n, size=b) / n
    return float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))


# ==================================================== Bayesian convergent =====
def identifiability_gate(cnt, actors, log):
    """GATES 1-3. Returns (ok, per_actor_ok, info). Refuses BEFORE any sampling."""
    keys = list(cnt)
    n_cells = len(keys)
    pairs = sorted(set(k[1] for k in keys))
    safes = sorted(set(k[4] for k in keys))
    nM, nP = len(actors), len(pairs)
    # alpha, bS, delta, gamma, theta per actor + sigma_u,u_z + sigma_d,d_z
    n_par = 5 * nM + (1 + nP) + (1 + nP)

    log("\n  IDENTIFIABILITY GATE (run before sampling; the first Study 1 Bayesian")
    log("  model was overparameterised - Claude's 4 stimuli exactly saturated 4")
    log("  parameters - and was replaced rather than reported).")
    log(f"    distinct data cells (actor x pair x level x partner x payoff) : {n_cells}")
    log(f"    free parameters                                              : {n_par}")
    log(f"      = 5 x {nM} actors (alpha,bS,delta,gamma,theta) + 2 x (1 + {nP} pairs)")
    gate1 = n_par < n_cells
    log(f"    GATE 1  params < cells : {'PASS' if gate1 else 'FAIL'}")

    # GATE 2: rank of the cell-level fixed-effects design matrix.
    aidx = {a: i for i, a in enumerate(actors)}
    sbar = float(np.mean([k[4] for k in keys]))
    X = []
    for (a, p, l, w, s) in keys:
        h = 1.0 if l == "high" else 0.0
        sm = 1.0 if w == "same" else 0.0
        row = []
        for a2 in actors:
            e = 1.0 if a == a2 else 0.0
            row += [e, e * (s - sbar), e * h, e * sm, e * h * sm]
        X.append(row)
    X = np.asarray(X, dtype=float)
    rank = int(np.linalg.matrix_rank(X))
    gate2 = rank == X.shape[1]
    log(f"    GATE 2  fixed-effects design matrix rank {rank} of {X.shape[1]} columns"
        f" : {'PASS' if gate2 else 'FAIL - structurally unidentified'}")

    # GATE 3: each actor needs a fully crossed 2x2 with data everywhere.
    per_actor = {}
    for a in actors:
        fc = four_cells(cnt, a)
        full = all(v[1] > 0 for v in fc.values())
        na = len(set(k[1] for k in keys if k[0] == a))
        per_actor[a] = full
        log(f"    GATE 3  {S.DISPLAY.get(a, a):16} 2x2 fully crossed with data "
            f"({na} pairs, {sum(1 for v in fc.values() if v[1] > 0)}/4 cells) : "
            f"{'PASS' if full else 'FAIL - theta not identified for this actor'}")
    ok = gate1 and gate2 and all(per_actor.values())
    if not ok:
        log("    -> REFUSING to fit or report the Bayesian model. This is the "
            "Study 1 lesson enforced, not a warning.")
    return ok, per_actor, dict(n_cells=n_cells, n_par=n_par, rank=rank,
                               ncol=int(X.shape[1]), n_pairs=nP, n_safe=len(safes))


def bayes_fit(rows, actors, log, draws=2000, tune=2000, chains=4, seed=SEED):
    """SECONDARY convergent model. Refuses to report on any gate failure."""
    try:
        import pymc as pm
        import arviz as az
    except Exception as exc:                                # noqa: BLE001
        log(f"\n  Bayesian model SKIPPED: pymc/arviz unavailable ({type(exc).__name__}: {exc})")
        log("  The primary permutation test above is unaffected.")
        return None

    pairs = sorted(set(r["pair"] for r in rows))
    pix = {p: i for i, p in enumerate(pairs)}
    aix = {a: i for i, a in enumerate(actors)}
    safe = np.array([r["safe"] for r in rows], float)
    sbar = float(safe.mean())
    y = np.array([r["y"] for r in rows], "int8")
    mi = np.array([aix[r["actor"]] for r in rows], "int32")
    pi = np.array([pix[r["pair"]] for r in rows], "int32")
    hi = np.array([1.0 if r["level"] == "high" else 0.0 for r in rows])
    sm = np.array([1.0 if r["partner"] == "same" else 0.0 for r in rows])
    nM, nP = len(actors), len(pairs)

    def build(no_alpha=False):
        with pm.Model() as m:
            alpha = (pm.math.constant(np.zeros(nM)) if no_alpha
                     else pm.Normal("alpha", 0.0, 1.5, shape=nM))
            bS = pm.Normal("bS", 0.0, 1.0, shape=nM)
            sig_u = pm.HalfNormal("sigma_u", 1.0)
            u_z = pm.Normal("u_z", 0.0, 1.0, shape=nP)
            u = pm.Deterministic("u_pair", sig_u * u_z)
            delta = pm.Normal("delta", 0.0, 1.0, shape=nM)
            sig_d = pm.HalfNormal("sigma_delta", 1.0)
            d_z = pm.Normal("d_z", 0.0, 1.0, shape=nP)
            d_p = pm.Deterministic("delta_pair", sig_d * d_z)
            gamma = pm.Normal("gamma", 0.0, 1.0, shape=nM)
            theta = pm.Normal("theta", 0.0, 1.0, shape=nM)
            eta = (alpha[mi] + bS[mi] * (safe - sbar) + u[pi]
                   + (delta[mi] + d_p[pi]) * hi + gamma[mi] * sm
                   + theta[mi] * hi * sm)
            pm.Bernoulli("y", p=pm.math.sigmoid(eta), observed=y)
        return m

    VARS = ["alpha", "bS", "delta", "gamma", "theta", "sigma_u", "sigma_delta"]

    def sample(m, ta=0.95):
        with m:
            return pm.sample(draws=draws, tune=tune, chains=chains, cores=4,
                             random_seed=seed, target_accept=ta, progressbar=False,
                             compute_convergence_checks=False)

    def diagnose(idata, names):
        s_ = az.summary(idata, var_names=[v for v in names if v in idata.posterior],
                        round_to=4)
        return (int(idata.sample_stats["diverging"].sum()),
                float(np.nanmax(s_["r_hat"])), float(np.nanmin(s_["ess_bulk"])))

    def sample_clean(build_kwargs, label):
        """Escalate target_accept until the fit is clean, then stop.

        Two hierarchical scales over only 5 pairs make a tight funnel, and a handful
        of divergences there is a step-size problem, not an unidentified posterior.
        Escalating target_accept is the standard remedy and it is a SAMPLER setting,
        not a change to the model or the priors - so GATE 4 keeps its full force:
        if 0.995 still diverges, the fit is refused rather than reported.
        """
        for ta in (0.95, 0.99, 0.995):
            idata = sample(build(**build_kwargs), ta=ta)
            div, rhat, ess = diagnose(idata, VARS)
            ok = div == 0 and rhat < 1.01 and ess > 400
            log(f"    [{label}] target_accept={ta:<5} div={div:3}  max R-hat={rhat:.4f}"
                f"  min ESS={ess:6.0f}   {'CLEAN' if ok else 'escalating'}")
            if ok:
                return idata, ta, div, rhat, ess
        return idata, ta, div, rhat, ess

    log("\n  FITTING hierarchical logistic with explicit theta = Stimulus x Partner")
    with build():
        pri = pm.sample_prior_predictive(draws=4000, random_seed=seed,
                                         var_names=["theta"])
    prior_th = np.asarray(pri.prior["theta"].values).reshape(-1, nM)
    idata, ta, div, rhat, ess = sample_clean({}, "primary")
    post = np.asarray(idata.posterior["theta"].values).reshape(-1, nM)
    clean = div == 0 and rhat < 1.01 and ess > 400
    log(f"    GATE 4  div={div}  max R-hat={rhat:.4f}  min ESS={ess:.0f}  "
        f"(target_accept={ta})  : "
        f"{'PASS' if clean else 'FAIL - refusing to report theta'}")
    if not clean:
        return dict(reported=False, reason="sampler diagnostics failed",
                    divergences=div, max_rhat=rhat, min_ess=ess, target_accept=ta)

    out = dict(reported=True, divergences=div, max_rhat=rhat, min_ess=ess,
               target_accept=ta, rows=[])
    log("\n  PRIMARY Bayesian parameter: theta[actor] (log-odds interaction)")
    for a, i in aix.items():
        v, pr = post[:, i], prior_th[:, i]
        w_post = float(np.percentile(v, 95) - np.percentile(v, 5))
        w_pri = float(np.percentile(pr, 95) - np.percentile(pr, 5))
        ratio = w_post / w_pri if w_pri else float("nan")
        flag = "" if ratio < 0.9 else "   <-- PRIOR-DOMINATED / NOT IDENTIFIED BY THE DATA"
        log(f"    theta[{S.DISPLAY.get(a, a):14}] median {np.median(v):+.3f}  "
            f"90% [{np.percentile(v,5):+.3f}, {np.percentile(v,95):+.3f}]  "
            f"P(>0)={float((v>0).mean()):.4f}   prior->post 90% width ratio "
            f"{ratio:.2f}{flag}")
        out["rows"].append(dict(param="theta", actor=a, actor_name=S.DISPLAY.get(a, a),
                                median=float(np.median(v)),
                                q05=float(np.percentile(v, 5)),
                                q95=float(np.percentile(v, 95)),
                                q025=float(np.percentile(v, 2.5)),
                                q975=float(np.percentile(v, 97.5)),
                                p_gt0=float((v > 0).mean()),
                                width_ratio_prior_to_post=ratio,
                                prior_dominated=bool(ratio >= 0.9)))
    for nm, var in (("delta (HIGH-LOW under DIFFERENT)", "delta"), ("gamma (SAME main)", "gamma")):
        arr = np.asarray(idata.posterior[var].values).reshape(-1, nM)
        for a, i in aix.items():
            v = arr[:, i]
            log(f"    {var}[{S.DISPLAY.get(a, a):14}] median {np.median(v):+.3f}  "
                f"90% [{np.percentile(v,5):+.3f}, {np.percentile(v,95):+.3f}]  "
                f"P(>0)={float((v>0).mean()):.4f}")
            out["rows"].append(dict(param=var, actor=a, actor_name=S.DISPLAY.get(a, a),
                                    median=float(np.median(v)),
                                    q05=float(np.percentile(v, 5)),
                                    q95=float(np.percentile(v, 95)),
                                    q025=float(np.percentile(v, 2.5)),
                                    q975=float(np.percentile(v, 97.5)),
                                    p_gt0=float((v > 0).mean()),
                                    width_ratio_prior_to_post="", prior_dominated=""))

    log("\n    RIDGE DIAGNOSTIC (soft, reported not gated): alpha[actor] and the pair")
    log("    intercepts u[pair] are only weakly separately identified, the same")
    log("    documented ridge as Study 1's B2. It cannot touch theta, a within-pair")
    log("    within-actor contrast that both alpha and u are common to. Refit with")
    log("    alpha fixed at 0 to confirm:")
    id2, _ta2, _d2, _r2, _e2 = sample_clean({"no_alpha": True}, "no-alpha")
    p2 = np.asarray(id2.posterior["theta"].values).reshape(-1, nM)
    for a, i in aix.items():
        v = p2[:, i]
        log(f"      no-alpha theta[{S.DISPLAY.get(a, a):14}] median {np.median(v):+.3f}  "
            f"90% [{np.percentile(v,5):+.3f}, {np.percentile(v,95):+.3f}]  "
            f"P(>0)={float((v>0).mean()):.4f}")
        out["rows"].append(dict(param="theta (no-alpha diagnostic)", actor=a,
                                actor_name=S.DISPLAY.get(a, a),
                                median=float(np.median(v)),
                                q05=float(np.percentile(v, 5)),
                                q95=float(np.percentile(v, 95)),
                                q025=float(np.percentile(v, 2.5)),
                                q975=float(np.percentile(v, 97.5)),
                                p_gt0=float((v > 0).mean()),
                                width_ratio_prior_to_post="", prior_dominated=""))
    return out


